-- search_path sengaja dikosongkan pada seluruh fungsi SECURITY DEFINER.
-- Dengan begitu nama tabel tidak bisa dibajak lewat skema lain, dan setiap
-- rujukan wajib ditulis lengkap (public.x / auth.x / pg_catalog.x).
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path='' as $$begin insert into public.profiles(id,nama) values(new.id,coalesce(new.raw_user_meta_data->>'nama',pg_catalog.split_part(new.email,'@',1))) on conflict(id) do nothing;return new;end$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path='' as $$select exists(select 1 from public.profiles where id=auth.uid() and role='admin')$$;

