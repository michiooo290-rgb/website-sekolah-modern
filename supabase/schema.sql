-- Versi lama fungsi ini hanya menerima lima argumen. Harus dibuang lebih
-- dulu: kalau dibiarkan, panggilan berargumen lima jadi ambigu karena versi
-- baru punya p_ip bernilai bawaan null.
drop function if exists public.submit_contact_message(text,text,text,text,text);

create or replace function public.submit_contact_message(p_nama text,p_email text,p_telepon text default null,p_subjek text default null,p_pesan text default null,p_ip text default null) returns void language plpgsql security definer set search_path='' as $$
declare
  v_email text:=lower(trim(coalesce(p_email,'')));
  v_nama text:=trim(coalesce(p_nama,''));
  v_pesan text:=trim(coalesce(p_pesan,''));
  v_ip text:=nullif(trim(coalesce(p_ip,'')),'');
begin
  if char_length(v_nama) not between 2 and 100 or char_length(v_email)>254 or v_email !~ '^[A-Za-z0-9.!#$%&''*+/=?^_`{|}~-]+@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+$' or char_length(coalesce(p_telepon,''))>30 or char_length(coalesce(p_subjek,''))>100 or char_length(v_pesan) not between 10 and 3000 then raise exception 'CONTACT_INVALID';end if;

  -- Urutan penguncian selalu email dulu, baru IP, supaya dua permintaan
  -- yang bersamaan tidak pernah saling mengunci (deadlock).
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_email,0));
  if v_ip is not null then perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('ip:'||v_ip,0));end if;

  if (select count(*) from public.pesan_kontak where lower(email)=v_email and tanggal>pg_catalog.now()-interval '15 minutes')>=3 then raise exception 'CONTACT_RATE_LIMITED';end if;
  if exists(select 1 from public.pesan_kontak where lower(email)=v_email and lower(trim(pesan))=lower(v_pesan) and tanggal>pg_catalog.now()-interval '1 hour') then raise exception 'CONTACT_RATE_LIMITED';end if;
  if v_ip is not null and (select count(*) from public.pesan_kontak where ip=v_ip and tanggal>pg_catalog.now()-interval '1 hour')>=8 then raise exception 'CONTACT_RATE_LIMITED';end if;

  insert into public.pesan_kontak(nama,email,telepon,subjek,pesan,ip) values(v_nama,v_email,nullif(trim(coalesce(p_telepon,'')),''),nullif(trim(coalesce(p_subjek,'')),''),v_pesan,v_ip);
end$$;
revoke all on function public.submit_contact_message(text,text,text,text,text,text) from public;
grant execute on function public.submit_contact_message(text,text,text,text,text,text) to anon,authenticated;

